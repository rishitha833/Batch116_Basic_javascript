var myflower = "Rose and lilly"   //we are declaring value
console.log(myflower)  //Rose and lilly

myflower = "sunflower"  //re-assigning
console.log(myflower)  //sunflower

var myflower = 6767  //re_declaring
console.log(myflower)  //6767

{
    console.log(myflower)  //accessing data outside into the block

    var myage = 22
    console.log(myage)  //accessing inside data inside block  //22
}

console.log(myage)  //accessing inside block into outside block  //22 